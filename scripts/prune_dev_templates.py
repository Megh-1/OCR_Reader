#!/usr/bin/env python
"""
Archive dev-database templates that scripts/seed_templates.py did not create.

Before the test suite ran against its own database it wrote throwaway
templates into the dev one. With no type_hint, Module 5 scans every known
template, so each leftover costs anchor OCR on every upload and is another
chance of a spurious match.

Templates are append-only, so this never deletes: it sets the is_archived
flag, which removes a doc_type from Module 5's scan and from the designer's
template list while keeping every version row readable. Reversible.

    python scripts/prune_dev_templates.py                       # list only - changes nothing
    python scripts/prune_dev_templates.py --archive             # list, then confirm, then archive
    python scripts/prune_dev_templates.py --archive --keep accuracy_harness_demo
    python scripts/prune_dev_templates.py --list-archived
    python scripts/prune_dev_templates.py --restore some_type another_type

"Created by seed_templates.py" means "its template_id is in seed_templates.ALL_TEMPLATES".
An already-running backend keeps skipping nothing until it is restarted:
it was started with the old code, and uvicorn runs without --reload.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from sqlalchemy import func, select  # noqa: E402

from app.db import SessionLocal  # noqa: E402
from app.models.extraction_result import ExtractionResultRecord  # noqa: E402
from app.models.template import TemplateRecord  # noqa: E402
from app.modules.template_store import set_template_archived  # noqa: E402
from scripts.seed_templates import ALL_TEMPLATES  # noqa: E402

SEEDED_IDS = frozenset(t.template_id for t in ALL_TEMPLATES)

# Names the test suite generates (uuid4 hex suffix, or a numbered drain
# helper). Anything else was named by a person and deserves an individual look.
_GENERATED_NAME = re.compile(r"^(test_doc|doc_a|doc_b)_[0-9a-f]{32}$|^drained_\d+$")


@dataclass
class Candidate:
    doc_type: str
    versions: int
    latest_version: int
    last_created: object  # date
    anchors: int
    fields: int
    extraction_results: int  # rows in extraction_results referencing this doc_type

    @property
    def generated(self) -> bool:
        return bool(_GENERATED_NAME.match(self.doc_type))


def _latest_rows(session) -> dict[str, tuple[TemplateRecord, int]]:
    """doc_type -> (its latest version's row, how many versions it has)."""
    rows = session.execute(select(TemplateRecord).order_by(TemplateRecord.doc_type, TemplateRecord.version)).scalars().all()
    latest: dict[str, tuple[TemplateRecord, int]] = {}
    for row in rows:  # ascending version, so the last row seen for a doc_type is its latest
        previous = latest.get(row.doc_type)
        latest[row.doc_type] = (row, (previous[1] if previous else 0) + 1)
    return latest


def find_candidates(session, keep: frozenset[str] = frozenset()) -> tuple[list[Candidate], int]:
    """Unarchived doc_types not created by the seed script and not explicitly
    kept, plus the count of doc_types already archived."""
    latest = _latest_rows(session)
    history = dict(
        session.execute(
            select(ExtractionResultRecord.template_id, func.count()).group_by(ExtractionResultRecord.template_id)
        ).all()
    )

    candidates: list[Candidate] = []
    already_archived = 0
    for doc_type, (row, version_count) in latest.items():
        if row.is_archived:
            already_archived += 1
            continue
        if doc_type in SEEDED_IDS or doc_type in keep:
            continue
        candidates.append(
            Candidate(
                doc_type=doc_type,
                versions=version_count,
                latest_version=row.version,
                last_created=row.created_at,
                anchors=len(row.config.get("anchors", [])),
                fields=len(row.config.get("fields", [])),
                extraction_results=history.get(doc_type, 0),
            )
        )
    return candidates, already_archived


def _print_review(candidates: list[Candidate], already_archived: int, keep: frozenset[str]) -> None:
    generated = [c for c in candidates if c.generated]
    named = [c for c in candidates if not c.generated]

    print(f"Seeded by scripts/seed_templates.py (always kept): {', '.join(sorted(SEEDED_IDS))}")
    if keep:
        print(f"Kept by --keep: {', '.join(sorted(keep))}")
    print(f"Already archived: {already_archived}")
    print()

    print(f"Generated by the test suite: {len(generated)} doc types, {sum(c.versions for c in generated)} versions")
    with_history = [c for c in generated if c.extraction_results]
    if with_history:
        print(f"  !! {len(with_history)} of these have extraction results recorded against them:")
        for c in with_history:
            print(f"     {c.doc_type}  ({c.extraction_results} result rows)")
    else:
        print("  none have extraction results recorded against them")
    for c in generated[:5]:
        print(f"  e.g. {c.doc_type}  v{c.latest_version}  {c.anchors} anchor(s), {c.fields} field(s)")
    if len(generated) > 5:
        print(f"  ... and {len(generated) - 5} more")
    print()

    print(f"Named by hand - REVIEW THESE: {len(named)}")
    for c in sorted(named, key=lambda c: c.doc_type):
        note = f", {c.extraction_results} extraction result(s)" if c.extraction_results else ""
        print(
            f"  {c.doc_type:28} {c.versions} version(s), latest v{c.latest_version} ({c.last_created}), "
            f"{c.anchors} anchor(s), {c.fields} field(s){note}"
        )
    print()


def _archive(candidates: list[Candidate]) -> None:
    rows = 0
    for c in candidates:
        rows += set_template_archived(c.doc_type, True)
    print(f"Archived {len(candidates)} doc types ({rows} version rows). Reverse with --restore <doc_type>.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--archive", action="store_true", help="archive the listed templates, after a typed confirmation")
    parser.add_argument("--keep", nargs="*", default=[], metavar="DOC_TYPE", help="doc types to leave alone")
    parser.add_argument("--restore", nargs="+", metavar="DOC_TYPE", help="un-archive these doc types")
    parser.add_argument("--list-archived", action="store_true", help="print archived doc types and exit")
    args = parser.parse_args()

    if args.restore:
        for doc_type in args.restore:
            changed = set_template_archived(doc_type, False)
            print(f"{doc_type}: {changed} version row(s) restored" if changed else f"{doc_type}: nothing to restore")
        return 0

    if args.list_archived:
        with SessionLocal() as session:
            archived = sorted(dt for dt, (row, _) in _latest_rows(session).items() if row.is_archived)
        print("\n".join(archived) if archived else "(none archived)")
        return 0

    keep = frozenset(args.keep)
    with SessionLocal() as session:
        candidates, already_archived = find_candidates(session, keep)

    _print_review(candidates, already_archived, keep)

    if not candidates:
        print("Nothing to archive.")
        return 0
    if not args.archive:
        print(f"Dry run - nothing changed. Re-run with --archive to archive these {len(candidates)}.")
        return 0

    try:
        answer = input(f"Type {len(candidates)} to archive these {len(candidates)} doc types (anything else aborts): ")
    except EOFError:
        answer = ""
    if answer.strip() != str(len(candidates)):
        print("Aborted - nothing changed.")
        return 1

    _archive(candidates)
    return 0


if __name__ == "__main__":
    sys.exit(main())
